/**
 * Pick a file extension for a media type.
 *
 * The asset route derives its Content-Type from the stored file's extension, so
 * a `.png` name on JPEG bytes is served as `image/png` and refused by strict
 * viewers. Unknown types fall back to `.bin`, which the route treats as a
 * download rather than something to render.
 *
 * @param {string} mime
 * @returns {string} an extension including the dot
 */
function extensionForMime(mime) {
  const key = text(mime).split(';')[0].trim().toLowerCase()
  return EXT_BY_MIME[key] ?? '.bin'
}

