/** `'shot-3'` / `'char-lin-yue'` / `'a-abc-123'` — anything path- and id-safe. */
const SAFE_REF = /^[A-Za-z0-9_-]{1,64}$/

/**
 * Resolve an asset record into the client-facing reference.
 *
 * The URL is built from ids and the stored FILE NAME only. It never embeds a
 * query parameter, an upstream URL, or anything derived from a channel, so a
 * key cannot travel inside an asset URL.
 *
 * @param {string} projectId
 * @param {object} asset
 * @returns {object}
 */
function projectAsset(projectId, asset) {
  const file = text(asset?.file)
  return {
    id: text(asset?.id),
    kind: text(asset?.kind) || ASSET_KIND.shotRef,
    ref: text(asset?.ref),
    url: file === '' ? '' : `${AIDRAMA_API.asset}/${encodeURIComponent(projectId)}/${encodeURIComponent(file)}`,
    name: text(asset?.name) || file,
    bytes: Number.isFinite(asset?.bytes) ? asset.bytes : 0,
    mime: text(asset?.mime),
    width: Number.isFinite(asset?.width) ? asset.width : undefined,
    height: Number.isFinite(asset?.height) ? asset.height : undefined,
    createdAt: Number.isFinite(asset?.createdAt) ? asset.createdAt : 0,
    origin: text(asset?.origin),
  }
}

/**
 * The per-project row the workbench project list renders.
 *
 * `listProjects()` returns cheap summaries WITHOUT `content`, but the workbench
 * needs the full stage rail. So this takes both the summary and (when the caller
 * has it) the full document, and adds `stages` from `stageView`. When no
 * document is available the stage rail is derived from the summary's counts so
 * the field is always present and always an array.
 *
 * @param {object} summary
 * @param {object | undefined} project full document, when already loaded
 * @param {(project: object) => Array<object>} stageViewFn
 * @returns {object}
 */
function projectRow(summary, project, stageViewFn) {
  const stages = project === undefined
    ? fallbackStageView(summary)
    : stageViewFn(project)
  return {
    id: text(summary?.id),
    title: text(summary?.title),
    logline: text(summary?.logline),
    aspectRatio: text(summary?.aspectRatio),
    episodes: Number.isFinite(summary?.episodes) ? summary.episodes : 1,
    shotSeconds: Number.isFinite(summary?.shotSeconds) ? summary.shotSeconds : 0,
    createdAt: Number.isFinite(summary?.createdAt) ? summary.createdAt : 0,
    updatedAt: Number.isFinite(summary?.updatedAt) ? summary.updatedAt : 0,
    stageCounts: isRecord(summary?.stageCounts) ? summary.stageCounts : {},
    stages,
    assetCount: Number.isFinite(summary?.assetCount) ? summary.assetCount : 0,
    videoTaskCount: Array.isArray(project?.videoTasks) ? project.videoTasks.length : 0,
  }
}

/**
 * Build a stage rail from a summary alone.
 *
 * Only used when a document could not be read (it vanished between the listing
 * and the read). Emitting the canonical six rows keeps the UI's rail from
 * collapsing, and `empty` is the honest status for a document we could not see.
 *
 * @param {object} summary
 * @returns {Array<object>}
 */
function fallbackStageView(summary) {
  const counts = isRecord(summary?.stageCounts) ? summary.stageCounts : {}
  return STAGES.map(stageId => {
    const meta = STAGE_META[stageId] ?? { id: stageId, label: stageId, short: stageId }
    return {
      id: stageId,
      label: meta.label,
      short: meta.short,
      status: STAGE_STATUS.empty,
      revision: 0,
      updatedAt: 0,
      note: '',
      ready: false,
      blocked: false,
      counted: Number.isFinite(counts[stageId]) ? counts[stageId] : 0,
    }
  })
}

