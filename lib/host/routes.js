/** A `- 标签：值` line, or nothing when the value is empty. */
function bullet(label, value) {
  const body = text(value)
  return body === '' ? '' : `- ${label}：${body}\n`
}

/**
 * Render a project as a readable 分镜脚本.
 *
 * Structure: 项目 → 想法 → 剧情 → 逐集逐场（场次头 / 时间 / 人物 / 动作 / 对白 /
 * 镜头表 / 时长）→ 设定集 → 资产清单. Every section is skipped when empty, so a
 * half-built project still exports something readable.
 *
 * @param {object} project
 * @returns {string}
 */
function exportMarkdown(project) {
  const content = isRecord(project?.content) ? project.content : {}
  const lines = []

  lines.push(`# ${text(project?.title) || '未命名短剧'}\n`)
  if (text(project?.logline) !== '') lines.push(`> ${text(project.logline)}\n`)
  lines.push(
    `- 项目 id：${text(project?.id)}\n` +
    `- 画幅：${text(project?.aspectRatio)}\n` +
    `- 集数：${Number.isFinite(project?.episodes) ? project.episodes : 1}\n` +
    `- 单镜时长：${Number.isFinite(project?.shotSeconds) ? project.shotSeconds : 0} 秒\n` +
    `- 风格 DNA：${text(project?.styleDna)}\n`,
  )

  const idea = isRecord(content.idea) ? content.idea : undefined
  if (idea !== undefined) {
    lines.push('\n## 一、想法梳理\n')
    lines.push(bullet('题材', idea.genre))
    lines.push(bullet('基调', idea.tone))
    lines.push(bullet('主角', idea.protagonist))
    lines.push(bullet('冲突', idea.conflict))
    lines.push(bullet('钩子', idea.hook))
    lines.push(bullet('结局', idea.ending))
    if (Array.isArray(idea.questions) && idea.questions.length > 0) {
      lines.push('- 待定问题：\n')
      for (const question of idea.questions) lines.push(`  - ${text(question)}\n`)
    }
  }

  const story = isRecord(content.story) ? content.story : undefined
  if (story !== undefined) {
    lines.push('\n## 二、剧情设计\n')
    lines.push(bullet('主题', story.theme))
    if (text(story.synopsis) !== '') lines.push(`\n${text(story.synopsis)}\n`)
    for (const act of Array.isArray(story.acts) ? story.acts : []) {
      if (!isRecord(act)) continue
      lines.push(`\n### ${text(act.name) || `第 ${text(act.no)} 幕`}\n`)
      lines.push(`${text(act.summary)}\n`)
    }
  }

  const script = isRecord(content.script) ? content.script : undefined
  if (script !== undefined) {
    lines.push('\n## 三、分场脚本\n')
    const episodes = Array.isArray(script.episodes) ? script.episodes : []
    if (episodes.length === 0) {
      for (const shot of Array.isArray(script.shots) ? script.shots : []) {
        if (!isRecord(shot)) continue
        lines.push(`- 镜 ${text(shot.seq)}｜${text(shot.shotSize)}｜${text(shot.cameraMove)}｜${text(shot.action)}\n`)
      }
    }
    episodes.forEach((episode, episodeIndex) => {
      if (!isRecord(episode)) return
      const epNo = Number.isFinite(Number(episode.no)) ? Number(episode.no) : episodeIndex + 1
      lines.push(`\n### 第 ${epNo} 集：${text(episode.title)}\n`)
      if (text(episode.hook) !== '') lines.push(`> 本集钩子：${text(episode.hook)}\n`)
      const scenes = Array.isArray(episode.scenes) ? episode.scenes : []
      scenes.forEach((scene, sceneIndex) => {
        if (!isRecord(scene)) return
        const scNo = Number.isFinite(Number(scene.no)) ? Number(scene.no) : sceneIndex + 1
        const heading = text(scene.slug) || [text(scene.location), text(scene.time)].filter(Boolean).join(' · ')
        lines.push(`\n#### 第 ${epNo}-${scNo} 场　${heading}\n`)
        lines.push(bullet('地点', scene.location))
        lines.push(bullet('时间', scene.time))
        lines.push(bullet('人物', Array.isArray(scene.characters) ? scene.characters.map(text).filter(Boolean).join('、') : ''))
        lines.push(bullet('动作', scene.action))
        lines.push(bullet('时长', Number.isFinite(Number(scene.durationSec)) ? `${Number(scene.durationSec)} 秒` : ''))

        const dialogue = Array.isArray(scene.dialogue) ? scene.dialogue : []
        if (dialogue.length > 0) {
          lines.push('\n**对白**\n\n')
          for (const entry of dialogue) {
            if (isRecord(entry)) lines.push(`${text(entry.who) || '旁白'}：${text(entry.line)}\n\n`)
            else lines.push(`${text(entry)}\n\n`)
          }
        }

        const shots = Array.isArray(scene.shots) ? scene.shots : []
        if (shots.length > 0) {
          lines.push('\n| 镜号 | 景别 | 机位/运动 | 画面 | 主体动作 | 时长 |\n')
          lines.push('| --- | --- | --- | --- | --- | --- |\n')
          shots.forEach((shot, shotIndex) => {
            if (!isRecord(shot)) return
            const no = Number.isFinite(Number(shot.no)) ? Number(shot.no) : shotIndex + 1
            const duration = Number.isFinite(Number(shot.durationSec)) ? `${Number(shot.durationSec)}s` : '—'
            lines.push(
              `| ${no} | ${text(shot.shot) || '—'} | ${text(shot.camera) || '—'} | ` +
              `${text(shot.description).replace(/\|/gu, '/')} | ${text(shot.motion).replace(/\|/gu, '/')} | ${duration} |\n`,
            )
          })
        }
      })
    })
  }

  const bible = isRecord(content.bible) ? content.bible : undefined
  if (bible !== undefined) {
    lines.push('\n## 四、设定集\n')
    const characters = Array.isArray(bible.characters) ? bible.characters : []
    if (characters.length > 0) {
      lines.push('\n### 人物\n')
      for (const character of characters) {
        if (!isRecord(character)) continue
        lines.push(`\n**${text(character.name)}**（${text(character.role)}）\n\n`)
        lines.push(bullet('外观', character.appearance))
        lines.push(bullet('性格', character.personality))
        lines.push(bullet('服装', character.costume))
        lines.push(bullet('弧光', character.arc))
      }
    }
    const scenes = Array.isArray(bible.scenes) ? bible.scenes : []
    if (scenes.length > 0) {
      lines.push('\n### 场景\n')
      for (const scene of scenes) {
        if (!isRecord(scene)) continue
        lines.push(`\n**${text(scene.name)}**\n\n`)
        lines.push(bullet('地点', scene.location))
        lines.push(bullet('时间', scene.timeOfDay))
        lines.push(bullet('氛围', scene.atmosphere))
        lines.push(bullet('光线', scene.lighting))
      }
    }
  }

  const assets = Array.isArray(project?.assets) ? project.assets : []
  if (assets.length > 0) {
    lines.push('\n## 五、视觉资产\n\n')
    lines.push('| 类型 | 关联 | 文件 | 说明 |\n| --- | --- | --- | --- |\n')
    for (const asset of assets) {
      if (!isRecord(asset)) continue
      lines.push(
        `| ${text(asset.kind)} | ${text(asset.ref)} | ${text(asset.file)} | ` +
        `${text(asset.name).replace(/\|/gu, '/')} |\n`,
      )
    }
  }

  return lines.join('')
}

/**
 * Render every image + video prompt as a copy-ready list.
 *
 * Purely local: it reads the project, builds prompts through `prompts.js`, and
 * never needs a channel, a key, or a network call.
 *
 * @param {object} prompts
 * @param {object} project
 * @returns {string}
 */
function exportPromptPack(prompts, project) {
  const lines = []
  lines.push(`# ${text(project?.title) || '未命名短剧'} · 提示词包\n`)
  lines.push(`\n画幅 ${text(project?.aspectRatio)}｜单镜 ${Number.isFinite(project?.shotSeconds) ? project.shotSeconds : 0} 秒\n`)
  lines.push(`\n风格 DNA：${text(project?.styleDna)}\n`)

  const bible = isRecord(project?.content?.bible) ? project.content.bible : {}
  const children = Array.isArray(bible.characters) ? bible.characters : []
  if (children.length > 0) {
    lines.push('\n## 人物三视图\n')
    for (const character of children) {
      if (!isRecord(character)) continue
      const built = promptForTarget(prompts, project, {
        kind: ASSET_KIND.characterSheet,
        ref: text(character.id),
        name: text(character.name),
      })
      lines.push(`\n### ${text(character.name) || text(character.id)}\n\n\`\`\`\n${built.prompt}\n\`\`\`\n`)
      if (built.negative !== '') lines.push(`\n负面：${built.negative}\n`)
    }
  }

  const scenes = Array.isArray(bible.scenes) ? bible.scenes : []
  if (scenes.length > 0) {
    lines.push('\n## 场景主图\n')
    for (const scene of scenes) {
      if (!isRecord(scene)) continue
      const built = promptForTarget(prompts, project, {
        kind: ASSET_KIND.sceneMaster,
        ref: text(scene.id),
        name: text(scene.name),
      })
      lines.push(`\n### ${text(scene.name) || text(scene.id)}\n\n\`\`\`\n${built.prompt}\n\`\`\`\n`)
    }
  }

  const shots = allShots(project)
  if (shots.length > 0) {
    lines.push('\n## 分镜参考图\n')
    for (const shot of shots) {
      const ref = text(shot.id)
      const built = promptForTarget(prompts, project, { kind: ASSET_KIND.shotRef, ref, name: ref })
      lines.push(`\n### ${ref}｜${text(shot.shotSize)}\n\n\`\`\`\n${built.prompt}\n\`\`\`\n`)
    }
  }

  const pack = buildPromptPack(prompts, project)
  if (pack.prompts.length > 0) {
    lines.push('\n## 逐镜视频提示词\n')
    for (const row of pack.prompts) {
      lines.push(`\n### ${row.ref}（第 ${row.shot} 镜）\n\n\`\`\`\n${row.prompt}\n\`\`\`\n`)
    }
  }

  return lines.join('')
}

/** Strip characters no filesystem (or download dialog) enjoys. */
function safeFilename(name) {
  const cleaned = text(name).replace(/[\\/:*?"<>|\u0000-\u001f]/gu, '_').replace(/\s+/gu, ' ').trim()
  return cleaned === '' ? '未命名短剧' : cleaned.slice(0, 80)
}

