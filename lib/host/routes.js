/**
 * Build the route family.
 *
 * @param {{
 *   store: object,
 *   stages: object,
 *   prompts: object,
 *   video: object,
 *   resolveConfig: () => object,
 *   generateImage: (request: object) => Promise<{ images: Array<{ b64: string, mime?: string }>, model?: string, channel?: string }>,
 *   log?: (message: string) => void,
 * }} deps
 * @returns {Array<{ kind: 'exact' | 'prefix', path: string, handler: (req: object, res: object) => Promise<void> }>}
 */
export function makeAidramaRoutes(deps) {
  const { store, stages, prompts, video } = deps
  const log = typeof deps.log === 'function' ? deps.log : () => {}

  /** Resolve config defensively: a resolver failure must not 500 the surface. */
  const config = () => {
    try {
      const value = deps.resolveConfig()
      return isRecord(value) ? value : {}
    } catch (error) {
      log(`resolveConfig failed: ${messageOf(error)}`)
      return {}
    }
  }

  /** Secrets of the current config, for literal scrubbing. */
  const secrets = () => secretsOf(config())

  /** Write a fail envelope with every configured secret removed. */
  const fail = (res, code, message) => {
    writeJson(res, 200, { ok: false, code, message: withoutSecrets(message, secrets()) })
  }

  /**
   * The loopback + method guard shared by every route.
   * @returns {boolean} true when the caller may proceed
   */
  const guard = (req, res, method) => {
    if (!isLoopbackRequest(req)) {
      writeJson(res, 403, { error: 'forbidden: loopback-only' })
      return false
    }
    if (req.method !== method) {
      writeJson(res, 405, { error: `method not allowed: ${req.method}` })
      return false
    }
    return true
  }

  /* ---------------------------------------------------------------- *
   * 1. /projects — list / create / get / save / delete / advance / rerun
   * ---------------------------------------------------------------- */

  /**
   * @param {object} req
   * @param {object} res
   */
  const handleProjects = async (req, res) => {
    if (!guard(req, res, 'POST')) return
    const body = await readJsonBody(req)
    if (body === undefined) {
      fail(res, 'bad-request', `请求体必须是合法 JSON 且不超过 ${MAX_JSON_BODY_BYTES} 字节`)
      return
    }

    const action = text(body.action)
    try {
      switch (action) {
        case 'list': {
          // `listProjects()` returns cheap summaries (no `content`), but the
          // workbench rail needs the real stage view — so read each document
          // once and build BOTH the row and its stage rail from that read.
          const summaries = await store.listProjects()
          const projects = []
          for (const summary of summaries) {
            const project = await store.readProject(text(summary?.id))
            projects.push(projectRow(summary, project, current => stages.stageView(current)))
          }
          writeJson(res, 200, { ok: true, projects })
          return
        }

        case 'create': {
          const project = stages.newProjectFrom({
            title: text(body.title),
            logline: text(body.logline),
            aspectRatio: text(body.aspectRatio),
            episodes: Number.isFinite(Number(body.episodes)) ? Number(body.episodes) : undefined,
            shotSeconds: Number.isFinite(Number(body.shotSeconds)) ? Number(body.shotSeconds) : undefined,
            styleDna: text(body.styleDna),
          })
          const value = config()
          if (text(project.styleDna) === '' && text(value.styleDna) !== '') project.styleDna = text(value.styleDna)
          if (text(project.aspectRatio) === '' && text(value.aspectRatio) !== '') project.aspectRatio = text(value.aspectRatio)
          await store.writeProject(project)
          writeJson(res, 200, { ok: true, project })
          return
        }

        case 'get': {
          const project = await store.readProject(text(body.id))
          if (project === undefined) {
            fail(res, 'not-found', `项目不存在：${text(body.id)}`)
            return
          }
          const view = stages.stageView(project)
          const assets = project.assets.map(asset => projectAsset(project.id, asset))
          const videoTasks = Array.isArray(project.videoTasks) ? project.videoTasks : []
          const taskIds = new Set(videoTasks.map(task => text(task?.assetId)).filter(Boolean))
          writeJson(res, 200, {
            ok: true,
            project,
            stages: view,
            assets,
            // Counts the workbench header shows; kept here so a single `get`
            // paints the whole workbench without a second round trip.
            videoTaskCount: videoTasks.length,
            persistedVideoAssets: assets.filter(asset => taskIds.has(asset.id)).length,
          })
          return
        }

        case 'save': {
          const project = body.project
          const problem = projectShapeProblem(project)
          if (problem !== '') {
            fail(res, 'bad-request', problem)
            return
          }
          const existing = await store.readProject(project.id)
          if (existing === undefined) {
            fail(res, 'not-found', `项目不存在：${project.id}，请先 create`)
            return
          }
          // Optimistic concurrency: a client that edited a document somebody
          // else has since saved must not silently clobber it.
          const expected = body.revision ?? body.updatedAt
          if (expected !== undefined && Number.isFinite(Number(expected)) && Number(existing.updatedAt) !== Number(expected)) {
            writeJson(res, 200, {
              ok: false,
              code: 'conflict',
              message: '该项目已被其他地方修改，请重新载入后再保存',
              current: existing.updatedAt,
              expected: Number(expected),
            })
            return
          }
          // `writeProject` mutates the object it is handed (it stamps updatedAt),
          // so it must receive a copy the caller does not also own.
          const saved = await store.writeProject({ ...project, schemaVersion: Number.isFinite(project.schemaVersion) ? project.schemaVersion : PROJECT_SCHEMA_VERSION })
          writeJson(res, 200, { ok: true, project: saved })
          return
        }

        case 'delete': {
          const removed = await store.deleteProject(text(body.id))
          if (!removed) {
            fail(res, 'not-found', `项目不存在：${text(body.id)}`)
            return
          }
          writeJson(res, 200, { ok: true })
          return
        }

        case 'advance': {
          const project = await store.readProject(text(body.id))
          if (project === undefined) {
            fail(res, 'not-found', `项目不存在：${text(body.id)}`)
            return
          }
          const stageId = text(body.stage)
          const verdict = stages.advanceGuard(project, stageId)
          if (!verdict.ok) {
            fail(res, 'stage-blocked', verdict.reason)
            return
          }
          // Advancing means "the content is current now": a stage that was only
          // stale because an upstream changed is promoted back to ready.
          const entry = project.stages[stageId]
          if (entry !== null && typeof entry === 'object') {
            entry.status = STAGE_STATUS.ready
            entry.updatedAt = Date.now()
          }
          await store.writeProject(project)
          writeJson(res, 200, {
            ok: true,
            project,
            ...(typeof verdict.warning === 'string' && verdict.warning !== '' ? { warning: verdict.warning } : {}),
          })
          return
        }

        case 'rerun': {
          const project = await store.readProject(text(body.id))
          if (project === undefined) {
            fail(res, 'not-found', `项目不存在：${text(body.id)}`)
            return
          }
          const stageId = text(body.stage)
          if (!isStageId(stageId)) {
            fail(res, 'bad-request', `未知阶段：${stageId}`)
            return
          }
          // Re-running an earlier stage keeps every later artifact but flags the
          // dependents stale. `markStageReady` deliberately does NOT do this.
          stages.markStageStale(project, stageId, text(body.reason) || '已标记需要重做')
          stages.invalidateAfter(project, stageId)
          await store.writeProject(project)
          writeJson(res, 200, { ok: true, project })
          return
        }

        default: {
          fail(res, 'bad-request', `未知 action：${action === '' ? '(空)' : action}`)
        }
      }
    } catch (error) {
      // A `TypeError` here is almost always a bad id reaching the store.
      fail(res, error instanceof TypeError ? 'bad-request' : 'projects-failed', messageOf(error))
    }
  }

  /* ---------------------------------------------------------------- *
   * 2. /stage — brief / commit / generate / clear
   * ---------------------------------------------------------------- */

  /**
   * Commit a text stage: normalize through stages.js, then mark ready.
   * @returns {Promise<object>}
   */
  const commitStage = async (project, stageId, payload, note) => {
    if (!TEXT_STAGES.includes(stageId)) {
      throw new TypeError(`阶段「${stageId}」不是文本阶段，不能用 commit 提交`)
    }
    stages.markStageReady(project, stageId, payload, note, { origin: ORIGIN.agent })
    return project
  }

  /**
   * Generate the visual assets for a batch of targets.
   *
   * ONE FAILED TARGET NEVER ABORTS THE BATCH: each target is wrapped, a failure
   * lands in `failures`, and the loop continues. That is the difference between
   * "3 of 12 frames failed" and "the whole generation was lost".
   *
   * @returns {Promise<{ assets: Array<object>, failures: Array<object> }>}
   */
  const generateVisual = async (project, targets, note) => {
    const value = config()
    const assets = []
    const failures = []

    // Mark the stage ready BEFORE storing any bytes.
    //
    // This ordering is load-bearing. `store.putAsset` reads the document, pushes
    // the asset and writes it back — so it composes correctly with ITSELF, but
    // NOT with a whole-document write from a stale in-memory copy. Writing
    // `project` after the batch would silently erase every asset the batch just
    // stored (a lost update). So the stage is recorded first, and `putAsset` is
    // the only writer afterwards.
    stages.markStageReady(
      project,
      'visual',
      { ...(isRecord(project.content.visual) ? project.content.visual : {}), generatedAt: Date.now() },
      note,
      { origin: ORIGIN.imageModel },
    )
    await store.writeProject(project)

    for (const target of targets) {
      const kind = text(target?.kind) || ASSET_KIND.shotRef
      const ref = text(target?.ref)
      try {
        if (ref === '') throw new TypeError('target.ref 不能为空')
        if (!SAFE_REF.test(ref)) throw new TypeError(`target.ref 不合法：${ref}`)

        const built = promptForTarget(prompts, project, { kind, ref, name: text(target?.name) })
        const result = await deps.generateImage({
          prompt: built.prompt,
          negative: built.negative,
          aspectRatio: text(project?.aspectRatio) || text(value.aspectRatio),
          styleDna: text(project?.styleDna) || text(value.styleDna),
          model: text(target?.model),
          // The target's identity travels with the request so a caller (and the
          // host entry's logging) can attribute a failure to the exact asset.
          kind,
          ref,
        })
        const first = Array.isArray(result?.images) ? result.images[0] : undefined
        const b64 = text(first?.b64)
        if (b64 === '') throw new Error('图像模型没有返回图片数据')

        // The stored extension must match the real bytes.
        //
        // This was hard-coded `.png` while `mime` came from the sniffed
        // payload, so a JPEG response was stored as `mime: image/jpeg` under a
        // `.png` name. The asset route rebuilds its Content-Type from the URL
        // extension, so the correct MIME never reached the browser and the file
        // was served as image/png — bytes that no strict viewer will render.
        // d1api.xin returns JPEG for roughly a quarter of images, so this was
        // not a corner case.
        const mime = text(first?.mime) || 'image/png'
        const record = await store.putAsset(project.id, {
          kind,
          ref,
          name: `${text(target?.name) || ref}${extensionForMime(mime)}`,
          bytes: b64,
          mime,
          ext: extensionForMime(mime),
          origin: ORIGIN.imageModel,
          meta: {
            prompt: built.prompt,
            negative: built.negative,
            model: text(result?.model),
            channel: text(result?.channel),
          },
        })
        assets.push(projectAsset(project.id, record))

        // Link the still back onto its shot. Without this the video stage reads
        // an empty first frame — see store.linkShotAsset.
        try {
          await store.linkShotAsset(project.id, ref, record.id, kind)
        } catch (error) {
          // A failed link must not lose the image the user already paid for.
          log(`linkShotAsset(${ref}) failed: ${messageOf(error)}`)
        }
      } catch (error) {
        failures.push({ kind, ref, message: withoutSecrets(messageOf(error), secrets()) })
      }
    }

    return { assets, failures }
  }

  const handleStage = async (req, res) => {
    if (!guard(req, res, 'POST')) return
    const body = await readJsonBody(req)
    if (body === undefined) {
      fail(res, 'bad-request', `请求体必须是合法 JSON 且不超过 ${MAX_JSON_BODY_BYTES} 字节`)
      return
    }

    const stageId = text(body.stage)
    const action = text(body.action)
    const payload = body.payload
    const note = text(body.note)

    try {
      // `brief` is answered without a project: the model reads the contract
      // BEFORE it has written anything, and a brief must never depend on state.
      if (action === 'brief') {
        if (TEXT_STAGES.includes(stageId)) {
          const brief = prompts.TEXT_STAGE_BRIEF[stageId]
          if (brief === undefined) {
            fail(res, 'bad-request', `阶段「${stageId}」没有任务说明`)
            return
          }
          writeJson(res, 200, { ok: true, brief })
          return
        }
        // A non-text stage has no JSON contract (visual is produced by an image
        // model, video by a video model). Handing back the template catalog is
        // far more useful than an error, and it is what the workbench lists.
        writeJson(res, 200, {
          ok: true,
          brief: {
            stage: stageId,
            text: false,
            note: TEXT_STAGES.includes(stageId)
              ? ''
              : `「${STAGE_META[stageId]?.label ?? stageId}」不是文本阶段：它由图像/视频模型产出，不由会话模型撰写。`,
            templates: prompts.TEMPLATE_CATALOG,
          },
        })
        return
      }

      const project = await store.readProject(text(body.projectId))
      if (project === undefined) {
        fail(res, 'not-found', `项目不存在：${text(body.projectId)}`)
        return
      }

      switch (action) {
        case 'commit': {
          await commitStage(project, stageId, payload, note)
          await store.writeProject(project)
          writeJson(res, 200, { ok: true, project })
          return
        }

        case 'generate': {
          if (!IMAGE_STAGES.includes(stageId)) {
            fail(res, 'bad-request', `阶段「${stageId}」不产生图像资产（只支持 ${IMAGE_STAGES.join(', ')}）`)
            return
          }
          const requested = Array.isArray(payload?.targets) ? payload.targets.filter(isRecord) : []
          const targets = requested.length > 0 ? requested : deriveVisualTargets(project)
          if (targets.length === 0) {
            fail(res, 'no-targets', '没有可生成的目标：请先完成「设定集」与「分场脚本」阶段，或在 payload.targets 里指定')
            return
          }
          const result = await generateVisual(project, targets, note)
          writeJson(res, 200, { ok: true, assets: result.assets, failures: result.failures })
          return
        }

        case 'clear': {
          if (!isStageId(stageId)) {
            fail(res, 'bad-request', `未知阶段：${stageId}`)
            return
          }
          const entry = project.stages[stageId]
          if (entry !== null && typeof entry === 'object') {
            entry.status = STAGE_STATUS.empty
            entry.note = ''
            entry.updatedAt = Date.now()
          }
          project.content[stageId] = null
          // Clearing an input invalidates everything built from it.
          stages.invalidateAfter(project, stageId)
          await store.writeProject(project)
          writeJson(res, 200, { ok: true, project })
          return
        }

        default: {
          fail(res, 'bad-request', `未知 action：${action === '' ? '(空)' : action}`)
        }
      }
    } catch (error) {
      fail(res, error instanceof TypeError ? 'bad-request' : 'stage-failed', messageOf(error))
    }
  }

  /* ---------------------------------------------------------------- *
   * 3. /video — submit / status / cancel / prompt-pack
   * ---------------------------------------------------------------- */

  const handleVideo = async (req, res) => {
    if (!guard(req, res, 'POST')) return
    const body = await readJsonBody(req)
    if (body === undefined) {
      fail(res, 'bad-request', `请求体必须是合法 JSON 且不超过 ${MAX_JSON_BODY_BYTES} 字节`)
      return
    }

    const action = text(body.action)
    const value = config()

    try {
      const project = await store.readProject(text(body.projectId))
      if (project === undefined) {
        fail(res, 'not-found', `项目不存在：${text(body.projectId)}`)
        return
      }

      switch (action) {
        case 'prompt-pack': {
          // Deliberately BEFORE any channel resolution: the pack is local, so it
          // must work with no video channel, no key and no network.
          const pack = buildPromptPack(prompts, project)
          writeJson(res, 200, { ok: true, pack })
          return
        }

        case 'submit': {
          const requested = Array.isArray(body.shotRefs) ? body.shotRefs.map(text).filter(Boolean) : []
          const shots = allShots(project)
          const wanted = requested.length > 0
            ? shots.filter(shot => requested.includes(text(shot.id)))
            : shots
          if (wanted.length === 0) {
            fail(res, 'no-targets', '没有可提交的镜头：请先完成「分场脚本」阶段，或在 shotRefs 里指定镜头')
            return
          }

          const channel = videoChannelFor(value, body.channelId)
          const tasks = []
          const failures = []
          for (const shot of wanted) {
            const ref = text(shot.id)
            try {
              const durationSec = Number.isFinite(Number(shot.durationSeconds))
                ? Number(shot.durationSeconds)
                : Number(project.shotSeconds)
              const submitted = await video.submitVideo({
                channel,
                prompt: text(shot.videoPrompt) !== ''
                  ? text(shot.videoPrompt)
                  : prompts.buildVideoPrompt({
                    shot: text(shot.shotSize),
                    camera: text(shot.cameraMove) || text(shot.camera),
                    motion: text(shot.action),
                    durationSec,
                    dialogue: text(shot.dialogue),
                    style: text(project.styleDna),
                  }),
                firstFrame: firstFrameDataUrl(project, shot),
                durationSec,
                aspectRatio: text(project.aspectRatio),
              })
              const task = {
                id: `vt-${shot.id ?? Date.now()}`,
                shotRef: ref,
                taskId: text(submitted?.taskId),
                status: text(submitted?.status) || 'queued',
                channelId: text(channel.id),
                protocol: text(channel.protocol),
                prompt: '',
                createdAt: Date.now(),
                updatedAt: Date.now(),
                raw: submitted?.raw ?? {},
              }
              tasks.push(task)
            } catch (error) {
              failures.push({ ref, message: withoutSecrets(messageOf(error), secrets()) })
            }
          }

          if (tasks.length > 0) {
            const existing = Array.isArray(project.videoTasks) ? project.videoTasks : []
            project.videoTasks = [...existing, ...tasks]
            stages.markStageReady(
              project,
              'video',
              { ...(isRecord(project.content.video) ? project.content.video : {}), submittedAt: Date.now(), tasks: project.videoTasks },
              '',
              { origin: ORIGIN.videoModel },
            )
            await store.writeProject(project)
          }
          writeJson(res, 200, { ok: true, tasks, failures })
          return
        }

        case 'status': {
          const taskId = text(body.taskId)
          const existing = (Array.isArray(project.videoTasks) ? project.videoTasks : [])
            .find(task => isRecord(task) && (text(task.taskId) === taskId || text(task.id) === taskId))
          if (existing === undefined) {
            fail(res, 'not-found', `视频任务不存在：${taskId}`)
            return
          }
          const channel = videoChannelFor(value, existing.channelId ?? body.channelId)
          const polled = await video.pollVideo({ channel, taskId: text(existing.taskId) })

          existing.status = text(polled?.status) || existing.status
          existing.updatedAt = Date.now()
          // The sibling module OMITS absent optional keys rather than nulling
          // them, so only assign what actually came back.
          if (polled?.videoUrl !== undefined) existing.videoUrl = polled.videoUrl
          if (polled?.coverUrl !== undefined) existing.coverUrl = polled.coverUrl
          if (polled?.error !== undefined) existing.error = withoutSecrets(polled.error, secrets())
          if (polled?.raw !== undefined) existing.raw = polled.raw

          // Persist only a TERMINAL state: an in-flight poll must not rewrite the
          // document on every tick (and a transient read must not "un-finish" a
          // task that already succeeded).
          if (VIDEO_TASK_TERMINAL.has(existing.status)) {
            await store.writeProject(project)
          }
          writeJson(res, 200, { ok: true, task: existing, terminal: VIDEO_TASK_TERMINAL.has(existing.status) })
          return
        }

        case 'cancel': {
          // Best effort by design: none of the supported protocols expose a
          // reliable cancel endpoint, so we release our own bookkeeping and
          // report success rather than pretending we stopped an upstream job.
          const taskId = text(body.taskId)
          const existing = (Array.isArray(project.videoTasks) ? project.videoTasks : [])
            .find(task => isRecord(task) && (text(task.taskId) === taskId || text(task.id) === taskId))
          if (existing !== undefined) {
            existing.status = 'failed'
            existing.error = '已在本机取消（上游任务可能仍在计费）'
            existing.updatedAt = Date.now()
            await store.writeProject(project)
          }
          writeJson(res, 200, { ok: true })
          return
        }

        default: {
          fail(res, 'bad-request', `未知 action：${action === '' ? '(空)' : action}`)
        }
      }
    } catch (error) {
      fail(res, error instanceof TypeError ? 'bad-request' : 'video-failed', messageOf(error))
    }
  }

  /* ---------------------------------------------------------------- *
   * 4. /asset (prefix) — stream stored bytes
   * ---------------------------------------------------------------- */

  /**
   * Parse `/api/dsh-aidrama/asset/<projectId>/<file>`.
   *
   * Both segments are matched against the store's own validators rather than
   * merely decoded, so `..`, an absolute path or a drive-relative name can never
   * reach the filesystem.
   *
   * @param {string} url
   * @returns {{ projectId: string, file: string } | undefined}
   */
  const assetRefFrom = (url) => {
    const path = String(url ?? '').split('?')[0].split('#')[0]
    if (!path.startsWith(`${AIDRAMA_API.asset}/`)) return undefined
    const rest = path.slice(AIDRAMA_API.asset.length + 1)
    const slash = rest.indexOf('/')
    if (slash <= 0) return undefined
    let projectId
    let file
    try {
      projectId = decodeURIComponent(rest.slice(0, slash))
      file = decodeURIComponent(rest.slice(slash + 1))
    } catch {
      return undefined
    }
    if (!store.isProjectId(projectId) || !store.isSafeFile(file)) return undefined
    return { projectId, file }
  }

  const handleAsset = async (req, res) => {
    if (!isLoopbackRequest(req)) {
      writeJson(res, 403, { error: 'forbidden: loopback-only' })
      return
    }
    if (req.method !== 'GET' && req.method !== 'HEAD') {
      writeJson(res, 405, { error: `method not allowed: ${req.method}` })
      return
    }

    const ref = assetRefFrom(req.url)
    if (ref === undefined) {
      writeJson(res, 404, { error: 'asset not found' })
      return
    }

    let stored
    try {
      stored = await store.readAsset(ref.projectId, ref.file)
    } catch {
      stored = undefined
    }
    if (stored === undefined) {
      writeJson(res, 404, { error: 'asset not found' })
      return
    }

    // Anything that is not a known media type is forced to a download so the
    // browser can never render it on the loopback origin.
    const declared = text(stored.mime).split(';')[0].trim().toLowerCase()
    const guessed = MIME_BY_EXT[ref.file.slice(ref.file.lastIndexOf('.')).toLowerCase()]
    const resolved = SAFE_INLINE_MIME[declared] ?? SAFE_INLINE_MIME[guessed] ?? 'application/octet-stream'
    const inline = SAFE_INLINE_MIME[resolved] !== undefined

    const data = Buffer.isBuffer(stored.data) ? stored.data : Buffer.from(stored.data ?? [])
    res.writeHead(200, {
      'content-type': inline ? resolved : 'application/octet-stream',
      'content-length': data.byteLength,
      'cache-control': 'private, max-age=3600',
      'referrer-policy': 'no-referrer',
      'x-content-type-options': 'nosniff',
      ...(inline ? {} : { 'content-disposition': `attachment; filename="${encodeURIComponent(ref.file)}"` }),
    })
    if (req.method === 'HEAD') {
      res.end()
      return
    }
    res.end(data)
  }

  /* ---------------------------------------------------------------- *
   * 5. /export — json / markdown / prompt-pack
   * ---------------------------------------------------------------- */

  const handleExport = async (req, res) => {
    if (!guard(req, res, 'POST')) return
    const body = await readJsonBody(req)
    if (body === undefined) {
      fail(res, 'bad-request', `请求体必须是合法 JSON 且不超过 ${MAX_JSON_BODY_BYTES} 字节`)
      return
    }

    try {
      const project = await store.readProject(text(body.projectId))
      if (project === undefined) {
        fail(res, 'not-found', `项目不存在：${text(body.projectId)}`)
        return
      }

      const base = safeFilename(project.title)
      const format = text(body.format) || 'json'
      switch (format) {
        case 'json': {
          writeJson(res, 200, {
            ok: true,
            filename: `${base}.json`,
            content: `${JSON.stringify(project, null, 2)}\n`,
          })
          return
        }
        case 'markdown':
        case 'md': {
          writeJson(res, 200, { ok: true, filename: `${base}-分镜脚本.md`, content: exportMarkdown(project) })
          return
        }
        case 'prompt-pack': {
          writeJson(res, 200, { ok: true, filename: `${base}-提示词包.md`, content: exportPromptPack(prompts, project) })
          return
        }
        default: {
          fail(res, 'bad-request', `未知导出格式：${format}（支持 json / markdown / prompt-pack）`)
        }
      }
    } catch (error) {
      fail(res, 'export-failed', messageOf(error))
    }
  }

  /* ---------------------------------------------------------------- *
   * 6. /config — the key-hygiene boundary
   * ---------------------------------------------------------------- */

  const handleConfig = async (req, res) => {
    if (!guard(req, res, 'POST')) return
    const body = await readJsonBody(req, MAX_JSON_BODY_BYTES)
    if (body === undefined) {
      fail(res, 'bad-request', `请求体必须是合法 JSON 且不超过 ${MAX_JSON_BODY_BYTES} 字节`)
      return
    }

    try {
      const value = config()
      // EXPLICIT PROJECTION. Never spread `value` or a channel here: this is the
      // one route whose entire purpose is to prove no key crosses the wire.
      writeJson(res, 200, {
        ok: true,
        config: {
          enabled: value.enabled !== false,
          announceToAgent: value.announceToAgent !== false,
          allowAgentGeneration: value.allowAgentGeneration !== false,
          aspectRatio: text(value.aspectRatio),
          shotSeconds: Number.isFinite(value.shotSeconds) ? value.shotSeconds : 0,
          styleDna: text(value.styleDna),
          channels: (Array.isArray(value.channels) ? value.channels : []).map(projectChannel),
          defaultChannelId: text(value.defaultChannelId),
          defaultModel: text(value.defaultModel),
          videoChannels: (Array.isArray(value.videoChannels) ? value.videoChannels : []).map(projectVideoChannel),
          defaultVideoChannelId: text(value.defaultVideoChannelId),
          stages: STAGES.map(stageId => ({
            id: stageId,
            label: STAGE_META[stageId].label,
            short: STAGE_META[stageId].short,
          })),
        },
      })
    } catch (error) {
      fail(res, 'config-failed', messageOf(error))
    }
  }

  return [
    { kind: 'exact', path: AIDRAMA_API.projects, handler: handleProjects },
    { kind: 'exact', path: AIDRAMA_API.stage, handler: handleStage },
    { kind: 'exact', path: AIDRAMA_API.video, handler: handleVideo },
    { kind: 'prefix', path: AIDRAMA_API.asset, handler: handleAsset },
    { kind: 'exact', path: AIDRAMA_API.export, handler: handleExport },
    { kind: 'exact', path: AIDRAMA_API.config, handler: handleConfig },
  ]
}

/**
 * Resolve a shot's first frame into a data URL for a video request.
 *
 * Reads the stored bytes and inlines them, because every supported protocol
 * either wants a public URL (which we cannot mint) or accepts a data URL. The
 * URL itself carries no credential — only the loopback asset path does.
 *
 * @param {object} project
 * @param {object} shot
 * @returns {Promise<string | undefined>}
 */
async function firstFrameDataUrl(project, shot) {
  const assetId = text(shot?.firstFrameAssetId) || text(shot?.imageAssetId)
  if (assetId === '') return undefined
  const asset = (Array.isArray(project?.assets) ? project.assets : [])
    .find(item => isRecord(item) && text(item.id) === assetId)
  if (asset === undefined) return undefined
  const file = text(asset.file)
  if (file === '') return undefined
  return `${AIDRAMA_API.asset}/${encodeURIComponent(text(project.id))}/${encodeURIComponent(file)}`
}
