/**
 * Verify that a project document is shaped enough for the stage engine.
 *
 * `store.readProject` already repairs documents on read, so this only guards the
 * `save` action, whose body is caller-supplied.
 *
 * @param {unknown} project
 * @returns {string} `''` when acceptable, else the reason
 */
function projectShapeProblem(project) {
  if (!isRecord(project)) return 'project 必须是一个对象'
  const isIdLike = value => typeof value === 'string' && /^[A-Za-z0-9_-]{1,64}$/.test(value)
  if (!isIdLike(project.id)) return 'project.id 必须是 1-64 位的字母、数字、下划线或短横线'
  if (!isRecord(project.stages)) return 'project.stages 必须是对象'
  if (!isRecord(project.content)) return 'project.content 必须是对象'
  if (!Array.isArray(project.assets)) return 'project.assets 必须是数组'
  if (!Array.isArray(project.videoTasks)) return 'project.videoTasks 必须是数组'
  return ''
}

/**
 * Derive the visual generation targets from the bible + script.
 *
 * Called only when the model did not pass `payload.targets`, so a bare "generate
 * the visuals" still produces a sensible full batch: one model sheet per
 * character, one master plate per scene, one reference frame per shot.
 *
 * @param {object} project
 * @returns {Array<{ kind: string, ref: string, name: string }>}
 */
function deriveVisualTargets(project) {
  const targets = []
  const seen = new Set()
  const push = (kind, ref, name) => {
    if (!SAFE_REF.test(ref) || seen.has(`${kind}:${ref}`)) return
    seen.add(`${kind}:${ref}`)
    targets.push({ kind, ref, name })
  }

  const bible = isRecord(project?.content?.bible) ? project.content.bible : {}
  for (const character of Array.isArray(bible.characters) ? bible.characters : []) {
    if (!isRecord(character)) continue
    push(ASSET_KIND.characterSheet, text(character.id), text(character.name))
  }
  for (const scene of Array.isArray(bible.scenes) ? bible.scenes : []) {
    if (!isRecord(scene)) continue
    push(ASSET_KIND.sceneMaster, text(scene.id), text(scene.name))
  }

  const script = isRecord(project?.content?.script) ? project.content.script : {}
  const episodes = Array.isArray(script.episodes) ? script.episodes : []
  episodes.forEach((episode, episodeIndex) => {
    if (!isRecord(episode)) return
    const epNo = Number.isFinite(Number(episode.no)) ? Number(episode.no) : episodeIndex + 1
    const scenes = Array.isArray(episode.scenes) ? episode.scenes : []
    scenes.forEach((scene, sceneIndex) => {
      if (!isRecord(scene)) return
      const scNo = Number.isFinite(Number(scene.no)) ? Number(scene.no) : sceneIndex + 1
      const shots = Array.isArray(scene.shots) ? scene.shots : []
      shots.forEach((shot, shotIndex) => {
        if (!isRecord(shot)) return
        const no = Number.isFinite(Number(shot.no)) ? Number(shot.no) : shotIndex + 1
        push(ASSET_KIND.shotRef, text(shot.id) || `shot-${epNo}-${scNo}-${no}`, `${text(scene.slug) || '场景'} · 镜 ${no}`)
      })
    })
  })

  // Only when the script stage really was a FLAT shot list (no episode tree):
  // `content.script.shots` is otherwise a lossy one-row ghost of the wrapper,
  // and generating from it would mint assets for a shot that does not exist.
  if (seen.size === 0) {
    for (const shot of Array.isArray(script.shots) ? script.shots : []) {
      if (!isRecord(shot)) continue
      push(ASSET_KIND.shotRef, text(shot.id), text(shot.action).slice(0, 24))
    }
  }

  return targets
}

/**
 * Build the image prompt for one visual target.
 *
 * @param {object} prompts
 * @param {object} project
 * @param {{ kind: string, ref: string, name?: string }} target
 * @returns {{ prompt: string, negative: string }}
 */
function promptForTarget(prompts, project, target) {
  const style = text(project?.styleDna)
  const aspectRatio = text(project?.aspectRatio)
  const bible = isRecord(project?.content?.bible) ? project.content.bible : {}

  if (target.kind === ASSET_KIND.characterSheet) {
    const character = (Array.isArray(bible.characters) ? bible.characters : [])
      .find(item => isRecord(item) && text(item.id) === target.ref)
    const source = isRecord(character) ? character : {}
    const merged = prompts.mergeLayers({
      styleDna: style,
      // The bible's per-character prompt is a human-authored override: it wins
      // over the generic template, which is exactly what `mergeLayers` is for.
      manual: text(source.sheetPrompt),
    })
    return {
      prompt: prompts.buildCharacterSheet({
        name: text(source.name) || target.name,
        description: text(source.appearance),
        hair: text(source.hair),
        face: text(source.face),
        body: text(source.body),
        outfit: text(source.outfit),
        accessory: text(source.accessory),
        style: merged.positive || style,
        aspectRatio,
      }),
      negative: merged.negative,
    }
  }

  if (target.kind === ASSET_KIND.sceneMaster) {
    const scene = (Array.isArray(bible.scenes) ? bible.scenes : [])
      .find(item => isRecord(item) && text(item.id) === target.ref)
    const source = isRecord(scene) ? scene : {}
    const merged = prompts.mergeLayers({
      styleDna: style,
      manual: text(source.masterPrompt),
    })
    return {
      prompt: prompts.buildSceneMaster({
        name: text(source.name) || target.name,
        description: text(source.description),
        lighting: text(source.lighting),
        composition: text(source.composition),
        style: merged.positive || style,
        aspectRatio,
      }),
      negative: merged.negative,
    }
  }

  // shot-ref / first-frame: locate the shot so the frame stays on-model.
  const shot = findShot(project, target.ref)
  const cast = Array.isArray(shot?.characters) ? shot.characters : []

  // Map EVERY reference a script might use to the character's FULL card.
  //
  // This previously mapped to the name string only (`id -> name`), which meant the
  // generated prompt could say "画面中的 林晚 必须严格沿用其角色设定三视图" while
  // never describing 林晚 at all — the appearance was thrown away one step before
  // the prompt was built. A live run on the real channel produced a long-haired
  // character in a black coat for a character specified as short-haired in a navy
  // uniform. The card has to survive this lookup for the prompt to constrain
  // anything.
  const characterById = {}
  for (const character of Array.isArray(bible.characters) ? bible.characters : []) {
    if (!isRecord(character)) continue
    const id = text(character.id)
    const name = text(character.name)
    // Both the stable id and the display name resolve to the card, because a
    // script may reference either (the normalizer keeps whatever the model wrote).
    if (id !== '') characterById[id] = character
    if (name !== '') characterById[name] = character
  }
  const sceneById = {}
  for (const scene of Array.isArray(bible.scenes) ? bible.scenes : []) {
    if (!isRecord(scene)) continue
    const id = text(scene.id)
    const name = text(scene.name)
    if (id !== '') sceneById[id] = scene
    // Alias by NAME as well. A script scene's `sceneId` is derived from its own
    // slug (e.g. `scene-subway-night`) and therefore can NEVER match a bible id
    // like `scene-subway`, so an id-only lookup silently dropped the scene's
    // lighting and composition from every shot prompt. Matching on the location
    // name is the reliable bridge between the two documents.
    if (name !== '') sceneById[name] = scene
  }
  // Resolve the bible scene by id first, then by the names the shot carries.
  // The id almost never matches (see above), so the name fallbacks are what
  // actually connect a shot to its scene master's lighting and composition.
  const bibleScene = sceneById[text(shot?.sceneId)]
    ?? sceneById[text(shot?.scene)]
    ?? sceneById[text(shot?.location)]
    ?? {}

  return {
    prompt: prompts.buildShotRef({
      description: text(shot?.action) || target.name || '本镜的剧情动作与画面结果',
      shot: text(shot?.shotSize),
      camera: text(shot?.camera) || text(shot?.cameraMove),
      lighting: text(bibleScene.lighting),
      composition: text(bibleScene.composition),
      style,
      characters: cast.map(name => characterById[text(name)] ?? { name: text(name) }),
      scene: text(shot?.scene) || text(bibleScene.name),
      aspectRatio,
    }),
    negative: prompts.mergeLayers({}).negative,
  }
}

/**
 * Find one shot inside a normalized project document.
 *
 * IMPORTANT — why the nested tree is searched FIRST: `stages.normalizeShots`
 * cannot see inside `{ episodes: [...] }`. Handed a whole script payload it
 * treats the wrapper as ONE bare shot, so `content.script.shots` may contain a
 * single ghost row with empty `action` / `sceneId` whose only real content is
 * the carried-through `episodes` key. The trustworthy copy of every shot lives
 * in the episode tree, so the tree wins and the flat list is only a fallback for
 * documents whose script stage really was a flat shot list.
 *
 * @param {object} project
 * @param {string} ref
 * @returns {object | undefined}
 */
function findShot(project, ref) {
  if (ref === '') return undefined
  for (const shot of shotsFromTree(project)) {
    if (text(shot.id) === ref) return shot
  }
  const script = isRecord(project?.content?.script) ? project.content.script : {}
  for (const shot of Array.isArray(script.shots) ? script.shots : []) {
    if (isRecord(shot) && text(shot.id) === ref) return shot
  }
  return undefined
}

/**
 * Every shot nested under `script.episodes[].scenes[].shots[]`, in playback
 * order, tagged with the ids the canonical `shot-<ep>-<sc>-<no>` scheme uses.
 *
 * @param {object} project
 * @returns {Array<object>} copies carrying `id` and `seq`
 */
function shotsFromTree(project) {
  const script = isRecord(project?.content?.script) ? project.content.script : {}
  // Index the flat list by id so asset links survive the tree rebuild.
  //
  // WHY: `store.linkShotAsset` writes `imageAssetId` onto the shots it can find,
  // and the flat `content.script.shots` is where the authored ids live. But the
  // episode tree is a RAW passthrough of what the model wrote — its shots carry
  // no `id` and therefore no `imageAssetId`, and the id here is SYNTHESIZED as
  // `shot-<ep>-<sc>-<no>`. So a shot generated from the tree had an id that
  // matched the asset's ref while carrying none of the asset's link: every video
  // task came out with `firstFrame: { kind: 'image', ref: {} }` and would have
  // rendered from no first frame at all. Rebuilding the id is not enough — the
  // link has to be carried across the rebuild.
  const linkedById = new Map()
  for (const row of Array.isArray(script.shots) ? script.shots : []) {
    if (!isRecord(row)) continue
    const id = text(row.id)
    if (id === '') continue
    const assetId = text(row.imageAssetId) || text(row.firstFrameAssetId)
    if (assetId !== '') linkedById.set(id, assetId)
  }

  const out = []
  const episodes = Array.isArray(script.episodes) ? script.episodes : []
  episodes.forEach((episode, episodeIndex) => {
    if (!isRecord(episode)) return
    const epNo = Number.isFinite(Number(episode.no)) ? Number(episode.no) : episodeIndex + 1
    const scenes = Array.isArray(episode.scenes) ? episode.scenes : []
    scenes.forEach((scene, sceneIndex) => {
      if (!isRecord(scene)) return
      const scNo = Number.isFinite(Number(scene.no)) ? Number(scene.no) : sceneIndex + 1
      const shots = Array.isArray(scene.shots) ? scene.shots : []
      shots.forEach((shot, shotIndex) => {
        if (!isRecord(shot)) return
        const no = Number.isFinite(Number(shot.no)) ? Number(shot.no) : shotIndex + 1
        // CAST INHERITANCE — this is what makes the character lock reachable.
        //
        // A shot in the episode tree usually has NO `characters` field; the cast is
        // declared once on the SCENE. Because this function is what `findShot`
        // searches first, returning the bare shot meant `cast` was always empty and
        // every shot-ref prompt silently fell back to the generic
        // "与设定集保持一致" clause — so no character's appearance ever reached the
        // image model. A live run produced a long-haired, black-coated character for
        // one specified as short-haired in a navy uniform.
        //
        // A shot-level cast still wins when present, so per-shot overrides work.
        const shotCast = Array.isArray(shot.characters) && shot.characters.length > 0
          ? shot.characters
          : (Array.isArray(scene.characters) ? scene.characters : [])
        const id = text(shot.id) || `shot-${epNo}-${scNo}-${no}`
        const linked = text(shot.imageAssetId) || text(shot.firstFrameAssetId) || linkedById.get(id) || ''
        out.push({
          ...shot,
          id,
          seq: Number.isFinite(Number(shot.seq)) ? Number(shot.seq) : out.length + 1,
          sceneId: text(shot.sceneId) || text(scene.slug),
          scene: text(shot.scene) || text(scene.location),
          location: text(shot.location) || text(scene.location),
          characters: shotCast,
          // Keep the asset link attached across the rebuild; without it the video
          // stage reads an empty first frame.
          ...(linked === '' ? {} : { imageAssetId: linked, firstFrameAssetId: linked }),
        })
      })
    })
  })
  return out
}

/**
 * Every shot of a project, flattened in playback order.
 *
 * Prefers the episode tree (see `findShot` for why) and falls back to
 * `content.script.shots` only when the tree holds nothing.
 *
 * @param {object} project
 * @returns {Array<object>}
 */
function allShots(project) {
  const tree = shotsFromTree(project)
  if (tree.length > 0) return tree

  const script = isRecord(project?.content?.script) ? project.content.script : {}
  const flat = (Array.isArray(script.shots) ? script.shots : []).filter(isRecord)
  if (flat.length > 0) return flat

  return flat
}

/**
 * Pick the video channel for a request.
 *
 * Falls back to the `prompt-pack` pseudo-channel, which needs no key, no apiUrl
 * and no network — that is what lets the video stage complete for a user who has
 * configured nothing at all.
 *
 * @param {object} config
 * @param {string} [channelId]
 * @returns {object}
 */
function videoChannelFor(config, channelId) {
  const channels = Array.isArray(config?.videoChannels) ? config.videoChannels : []
  const wanted = text(channelId)
  return channels.find(channel => channel.id === wanted)
    ?? channels.find(channel => channel.id === config?.defaultVideoChannelId)
    ?? channels[0]
    ?? {
      id: 'prompt-pack',
      name: '仅提示词包（无密钥回退）',
      protocol: VIDEO_PROTOCOL.promptPack,
      apiUrl: '',
      apiKey: '',
      model: '',
    }
}

/**
 * Build one video prompt per shot for a project, without touching the network.
 *
 * Shared by the `prompt-pack` video action and the `prompt-pack` export format so
 * the two can never drift.
 *
 * @param {object} prompts
 * @param {object} project
 * @returns {{ prompts: Array<object>, note: string }}
 */
function buildPromptPack(prompts, project) {
  const shots = allShots(project)
  const rows = shots.map((shot, index) => {
    const seq = Number.isFinite(Number(shot.seq)) ? Number(shot.seq) : index + 1
    const ref = text(shot.id) || `shot-${seq}`
    const durationSec = Number.isFinite(Number(shot.durationSeconds))
      ? Number(shot.durationSeconds)
      : (Number.isFinite(Number(project?.shotSeconds)) ? Number(project.shotSeconds) : undefined)
    const authored = text(shot.videoPrompt)
    const prompt = authored !== ''
      ? authored
      : prompts.buildVideoPrompt({
        shot: text(shot.shotSize),
        camera: text(shot.cameraMove) || text(shot.camera),
        motion: text(shot.action),
        durationSec,
        dialogue: text(shot.dialogue),
        style: text(project?.styleDna),
      })
    return { ref, shot: seq, prompt }
  })

  return {
    prompts: rows,
    note: rows.length === 0
      ? '项目里还没有分镜：先完成「分场脚本」阶段再导出提示词包。'
      : `共 ${rows.length} 个镜头。把提示词与对应首帧图粘到任意视频模型即可（无需 API 密钥）。`,
  }
}

