/**
 * Collect every secret the current config holds, so responses and logs can be
 * scrubbed literally rather than heuristically.
 *
 * @param {object} config
 * @returns {string[]}
 */
function secretsOf(config) {
  const out = []
  for (const channel of config?.channels ?? []) {
    if (typeof channel?.apiKey === 'string' && channel.apiKey !== '') out.push(channel.apiKey)
  }
  for (const channel of config?.videoChannels ?? []) {
    if (typeof channel?.apiKey === 'string' && channel.apiKey !== '') out.push(channel.apiKey)
  }
  return out
}

