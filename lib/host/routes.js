/** Human-readable text from an unknown thrown value. */
function messageOf(error) {
  return error instanceof Error ? error.message : String(error)
}

/** Whether `value` is a non-null, non-array object. */
function isRecord(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
}

/** A trimmed string, or `''`. */
function text(value) {
  if (typeof value === 'string') return value.trim()
  if (typeof value === 'number' && Number.isFinite(value)) return String(value)
  return ''
}

/**
 * Scrub anything credential-shaped out of a string that is about to be
 * returned to a client or written to a log.
 *
 * The sibling modules already scrub their own upstream errors, but this layer
 * is the last one before the wire, so it repeats the pass: a `Bearer …` header,
 * an `api_key=` query fragment or an `sk-…` literal must not survive here even
 * if some future caller forgets.
 *
 * @param {unknown} value
 * @returns {string}
 */
function scrub(value) {
  return String(value ?? '')
    .replace(/\b(?:Bearer|Token|token)\s+[A-Za-z0-9._~+/=-]{6,}/gi, 'Bearer ****')
    .replace(/((?:"?(?:api[_-]?key|access[_-]?token|authorization|apikey)"?\s*[:=]\s*"?))[^"\s,}&]{4,}/gi, '$1****')
    .replace(/\bsk-[A-Za-z0-9._-]{6,}/gi, 'sk-****')
}

/**
 * Remove every configured secret from a string by literal replacement.
 *
 * Regexes alone cannot catch a key echoed verbatim inside a prose message, so
 * when we know the deployment's secrets we delete them literally. This is the
 * belt to `scrub`'s braces.
 *
 * @param {string} value
 * @param {string[]} secrets
 * @returns {string}
 */
function withoutSecrets(value, secrets) {
  let out = String(value ?? '')
  for (const secret of secrets) {
    if (typeof secret !== 'string' || secret.length < 4) continue
    out = out.split(secret).join('****')
  }
  return scrub(out)
}

/* ------------------------------------------------------------------ *
 * Request guards
 * ------------------------------------------------------------------ */

/**
 * Loopback literal check plus browser same-origin markers.
 *
 * Mirrors dsh-imagegen's `isLoopbackRequest` (which itself mirrors dsh-ssh)
 * exactly: the socket address must be a loopback literal, the Host header must
 * be a loopback host, an explicit cross-site fetch is refused, and a present
 * Origin must match the Host.
 *
 * @param {object} request
 * @returns {boolean}
 */
function isLoopbackRequest(request) {
  const address = request.socket?.remoteAddress
  if (address !== '127.0.0.1' && address !== '::1' && address !== '::ffff:127.0.0.1') return false
  const host = request.headers?.host
  if (typeof host !== 'string') return false
  let hostUrl
  try {
    hostUrl = new URL(`http://${host}`)
  } catch {
    return false
  }
  if (hostUrl.hostname !== '127.0.0.1' && hostUrl.hostname !== 'localhost' && hostUrl.hostname !== '[::1]') return false
  if (request.headers['sec-fetch-site'] === 'cross-site') return false
  const origin = request.headers.origin
  if (origin === undefined) return true
  try {
    return new URL(origin).host === hostUrl.host
  } catch {
    return false
  }
}

/** One JSON response. */
function writeJson(res, status, body) {
  const payload = JSON.stringify(body)
  res.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'referrer-policy': 'no-referrer',
  })
  res.end(payload)
}

/** A handled failure: always 200, always an envelope. */
function writeFail(res, code, message) {
  writeJson(res, 200, { ok: false, code, message: scrub(message) })
}

/** A handled success. */
function writeOk(res, body = {}) {
  writeJson(res, 200, { ok: true, ...body })
}

/**
 * Read a JSON request body, refusing to buffer more than `maxBytes`.
 *
 * Returns `undefined` both for "too large" and for "unparseable"; the caller
 * reports one `bad-request`, because distinguishing them to a client leaks
 * nothing useful and the cap is the security property that matters.
 *
 * @param {object} req
 * @param {number} [maxBytes]
 * @returns {Promise<object | undefined>}
 */
async function readJsonBody(req, maxBytes = MAX_JSON_BODY_BYTES) {
  const chunks = []
  let size = 0
  try {
    for await (const chunk of req) {
      const buffer = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk)
      size += buffer.length
      if (size > maxBytes) return undefined
      chunks.push(buffer)
    }
  } catch {
    return undefined
  }
  try {
    const parsed = JSON.parse(Buffer.concat(chunks).toString('utf8'))
    return isRecord(parsed) ? parsed : undefined
  } catch {
    return undefined
  }
}

