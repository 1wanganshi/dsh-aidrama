/**
 * dsh-aidrama — host HTTP route family.
 *
 * This is the SINGLE implementation of every project operation. The browser half
 * and the Agent tools both drive these handlers (the Agent path synthesises a
 * req/res pair in lib/index.js), so a commit or a generation batch can never
 * mean two different things depending on who asked.
 *
 * Contract rules, enforced here rather than by convention:
 *
 *  - EVERY route is LOOPBACK-ONLY. `isLoopbackRequest` mirrors dsh-imagegen
 *    exactly, including the browser same-origin markers, so a hostile page in
 *    the user's own browser cannot reach the local API.
 *  - NO API KEY EVER LEAVES THE HOST. `/config` projects channels through an
 *    explicit allow-list and reports only the boolean `hasKey`; asset URLs carry
 *    a file name and nothing else; every error message is scrubbed before it is
 *    written. A key must not be reconstructible from any response.
 *  - A HANDLED failure answers 200 with `{ ok: false, code, message }`. Non-200
 *    is reserved for the loopback/method guards and the asset 404.
 *  - Request bodies are capped at MAX_JSON_BODY_BYTES; an oversized body is
 *    never buffered in full.
 *
 * Plain ESM, zero dependencies, no build step.
 */

